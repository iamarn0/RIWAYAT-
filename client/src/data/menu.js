export function getDish(id) {
  return menu.find((item) => item.id === id);
}

export function getFeaturedDishes() {
  return menu.filter((item) => item.featured).sort((a, b) => a.featured - b.featured);
}

export function dishesForRegion(region) {
  return menu.filter((item) => item.region === region);
}
